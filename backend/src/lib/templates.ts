export function templateFor(platform: PlatformId): MockTemplate {
  return MOCK_TEMPLATES.find((t) => t.platforms.includes(platform)) ?? MOCK_TEMPLATES.find((t) => t.fallback)!;
}

export function segmentsFromLines(lines: string[]): { start: number; end: number; text: string }[] {
  let cursor = 0.4;
  return lines.map((line) => {
    const speech = Math.max(3, Math.round((line.length / 4.2) * 10) / 10);
    const gap = 0.25;
    const start = cursor;
    const end = start + speech;
    cursor = end + gap;
    return { start, end, text: line };
  });
}
